import argparse
import csv

from preflight.eval.registry import RESULTS, RUNS
from preflight.eval.run import void_runs
from preflight.eval.split import load_split

FINAL = RESULTS / "final.md"
# the figures the submission quotes, in the order the table shows them
ROWS = {
    "ad_recall": "Positive ads flagged",
    "claim_recall_carried": "Breaching claims caught with a matching rule (claims the item carries)",
    "claim_recall_carried_by_chance": "same flags, rules cited at random",
    "claim_recall_carried_weighted": "same, each catch weighted by its share of matching rules",
    "rule_precision": "Cited rules that match a rule the ground truth names",
    "near_miss_caught": "Near-miss lines caught",
    "clean_lines_flagged": "Clean lines flagged on near-miss items",
    "negative_ads_flagged": "Negative ads flagged",
    "unmatched_lines_per_positive_ad": "Flagged lines matching no breaching claim, per positive ad",
    "screen_cost_usd": "Cost of the run",
}
# the test bar (docs/notes/decisions.md, 2 and 4 Nov 2026): what a test screening run must meet
BAR = {
    "ad_recall": ("at least 48 of 59", lambda h, t: h >= 48),
    "claim_recall_carried": ("at least 70%", lambda h, t: h >= 0.7 * t),
    "near_miss_caught": ("at least 9 of 10", lambda h, t: h >= 9),
    "clean_lines_flagged": ("at most 10%", lambda h, t: h <= 0.1 * t),
    "negative_ads_flagged": ("at most 1 of 20", lambda h, t: h <= 1),
}
# a test negative whose copy omits what its register entries require, so a flag on it is correct (4 Nov 2026)
FLAWED_NEGATIVE = "T14"
HEADER = "# Results\n\nGenerated by `python -m preflight.eval.final` from `results/runs.csv`; not edited by hand.\n"
NOTE = ("Figures are hits / total with a 95% interval, exact for a count of ads, else a bootstrap over ads. "
        "How each run was set up, and any change between test attempts, is in `docs/notes/decisions.md`.")
PROVENANCE = ("created_at", "git_sha", "split", "part", "stage", "model", "prompt", "effort", "snapshots")


def load_runs(run_ids: list[str]) -> dict[str, dict[str, dict]]:
    with RUNS.open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    void = void_runs()
    runs = {}
    for run_id in run_ids:
        if reason := void.get(run_id):
            raise SystemExit(f"{run_id} is void ({reason})")
        metrics = {r["metric"]: r for r in rows if r["run_id"] == run_id}
        if not metrics:
            raise SystemExit(f"{run_id} is not in {RUNS.name}")
        first = next(iter(metrics.values()))
        # rule 5: a reported test figure must trace to a commit
        if first["part"] == "test" and first["git_sha"].endswith("-dirty"):
            raise SystemExit(f"{run_id} ran on the test part from a dirty tree")
        runs[run_id] = metrics
    return runs


def cell(row: dict | None) -> str:
    if row is None:
        return "–"
    hits, total = float(row["hits"]), float(row["total"])
    if row["part"] == "test" and row["stage"] == "screen" and row["metric"] in BAR:
        met = BAR[row["metric"]][1](hits, total)
        return figure(row, hits, total) + (" **met**" if met else " **not met**")
    return figure(row, hits, total)


def figure(row: dict, hits: float, total: float) -> str:
    if row["metric"] == "screen_cost_usd":
        return f"${hits:.2f} for {total:g} items"
    if not row["low"]:
        return f"{hits:g} over {total:g} ads ({hits / total:.2f} each)"
    return f"{hits:g} / {total:g} ({hits / total:.1%}) [{float(row['low']):.3f}, {float(row['high']):.3f}]"


def negatives_by_cohort(run_id: str, split: str, part: str) -> str | None:
    # the P60 pass mark: the split v1 negatives and the ones added in v2 are also given apart
    path = RESULTS / "runs" / f"{run_id}.csv"
    if split != "v2" or not path.exists():
        return None
    with path.open(newline="", encoding="utf-8") as f:
        negatives = [r for r in csv.DictReader(f) if r["label"] == "negative"]
    v1 = set(getattr(load_split("v1"), part))
    parts = []
    for name, cohort in (("split v1", [r for r in negatives if r["item_id"] in v1]),
                         ("added in v2", [r for r in negatives if r["item_id"] not in v1]),
                         (f"without {FLAWED_NEGATIVE}", [r for r in negatives if r["item_id"] != FLAWED_NEGATIVE])):
        parts.append(f"{sum(int(r['flags']) > 0 for r in cohort)} of {len(cohort)} {name}")
    return ", ".join(parts)


def heading(run_id: str, metrics: dict[str, dict]) -> str:
    first = next(iter(metrics.values()))
    if first["part"] == "test":
        return f"{first['stage']} `{run_id}`, {first['split']} test"
    return f"{first['stage']} `{run_id}`, {first['split']} dev split (prompts tuned on it)"


def render(runs: dict[str, dict[str, dict]]) -> str:
    lines = [HEADER]
    lines += ["| Measure | Pass mark | " + " | ".join(heading(i, m) for i, m in runs.items()) + " |"]
    lines += ["|---" * (len(runs) + 2) + "|"]
    for metric, label in ROWS.items():
        if all(metric not in m for m in runs.values()):
            continue
        mark = BAR[metric][0] if metric in BAR else ""
        lines += [f"| {label} | {mark} | " + " | ".join(cell(m.get(metric)) for m in runs.values()) + " |"]
    firsts = {run_id: next(iter(m.values())) for run_id, m in runs.items()}
    cohorts = [negatives_by_cohort(i, r["split"], r["part"]) or "–" for i, r in firsts.items()]
    if any(c != "–" for c in cohorts):
        lines += ["| Negative ads flagged, by cohort | | " + " | ".join(cohorts) + " |"]
    lines += ["", NOTE, ""]
    lines += ["## Runs", ""]
    for run_id, first in firsts.items():
        lines += [f"- `{run_id}`: " + "; ".join(f"{k} {first[k]}" for k in PROVENANCE if first[k])]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Write results/final.md from registered runs.")
    parser.add_argument("run_ids", nargs="+", help="registered run IDs, one column each")
    args = parser.parse_args()
    FINAL.write_text(render(load_runs(args.run_ids)), encoding="utf-8")
    print(f"wrote {FINAL.relative_to(RESULTS.parent)}")


if __name__ == "__main__":
    main()
